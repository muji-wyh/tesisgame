'use strict';
const fs = require('node:fs');
const path = require('node:path');
const codec = require('./codec.cjs');
const REPO_ROOT = path.resolve(__dirname, '../..');
const SCHEMA_VERSION = 1;
const POLICY_VERSION = 'ordinary-lexical-v3';
const CONTEXT_BOUNDARY = 'containing-modules-v1';
const INDEX_KIND = 'compiled_professional_release_v1';
const MODULE_KIND = 'compiled_professional_module_v1';
const RELEASE_KIND = 'professional_domain_application_release_v1';
const TRUST_STATUS = 'application_build_audited';
const DECISIONS = 'data/professional/domain-policy/decisions.json';
const GENERATED = 'data/professional/domain-policy/generated';
const PIN = 'scripts/professional_domain_release.gd';
const LIMITS = Object.freeze({descriptor:262144,index:262144,themes:262144,manifest:262144,payload:524288,
  coldBytes:2097152,coldOpens:16,fullFiles:4096,fullBytes:268435456,fullFileBytes:33554432,fullDepth:16,fullEntries:8192});
const DEPENDENCIES = ['tools/validate-professional-content.cjs','tools/validate-theme-motion.cjs',
  'tools/professional-picture-pools.cjs','web/professional-media.js'];

function assertAncestors(filename, allowMissingLeaf = false) {
  const absolute = path.resolve(filename), parsed = path.parse(absolute);
  let cursor = parsed.root;
  for (const segment of absolute.slice(parsed.root.length).split(path.sep).filter(Boolean)) {
    cursor = path.join(cursor, segment);
    if (allowMissingLeaf && cursor === absolute && !fs.existsSync(cursor)) return;
    const stat = fs.lstatSync(cursor);
    if (stat.isSymbolicLink() || cursor !== absolute && !stat.isDirectory()) throw Error('Symlink or non-directory ancestor rejected: ' + cursor);
  }
}
function contractInventory() {
  const names = [];
  function walk(relative) {
    const absolute = path.join(REPO_ROOT, relative); assertAncestors(absolute);
    for (const entry of fs.readdirSync(absolute, {withFileTypes:true})) {
      const name = relative + '/' + entry.name;
      if (!/^[A-Za-z0-9_.-]+$/.test(entry.name) || entry.isSymbolicLink()) throw Error('Unsafe domain contract entry');
      if (entry.isDirectory()) walk(name);
      else if (entry.isFile() && entry.name.endsWith('.cjs')) names.push(name);
      else throw Error('Unexpected domain contract entry: ' + name);
    }
  }
  walk('tools/professional-domain');
  return [...names, ...DEPENDENCIES].sort().map(relative => {
    const filename = path.join(REPO_ROOT, relative); assertAncestors(filename);
    const raw = codec.readBounded(filename, LIMITS.fullFileBytes);
    return {path:relative, bytes:raw.length, sha256:codec.sha256(raw)};
  });
}
function assertEmptyDecisions(value) {
  codec.exactKeys(value, ['schema_version','policy_version','context_boundary','entries'], 'initial decisions');
  if (value.schema_version !== SCHEMA_VERSION || value.policy_version !== POLICY_VERSION ||
      value.context_boundary !== CONTEXT_BOUNDARY || !Array.isArray(value.entries) || value.entries.length) {
    throw Error('Initial application release requires explicitly empty decisions; exceptions are not authorized');
  }
}
function disjoint(first, second) {
  const identity = value => process.platform === 'win32' ? path.resolve(value).toLowerCase() : path.resolve(value);
  const a = identity(first), b = identity(second);
  if (a === b || a.startsWith(b + path.sep) || b.startsWith(a + path.sep)) throw Error('Source and output roots must be disjoint');
}
function pinSource(descriptor) {
  if (!Number.isSafeInteger(descriptor.bytes) || descriptor.bytes < 1 || descriptor.bytes > LIMITS.descriptor ||
      !/^[a-f0-9]{64}$/.test(descriptor.sha256)) throw Error('Invalid application descriptor pin');
  return Buffer.from('extends RefCounted\n## Generated by the independently audited Professional domain package.\n\n' +
    'const SCHEMA_VERSION: int = 1\n' +
    'const POLICY_VERSION: String = "' + POLICY_VERSION + '"\n' +
    'const CONTEXT_BOUNDARY: String = "' + CONTEXT_BOUNDARY + '"\n' +
    'const DESCRIPTOR_PATH: String = "res://' + GENERATED + '/release.json"\n' +
    'const DESCRIPTOR_BYTES: int = ' + descriptor.bytes + '\n' +
    'const DESCRIPTOR_SHA256: String = "' + descriptor.sha256 + '"\n' +
    'const GENERATED_ROOT: String = "res://' + GENERATED + '/"\n', 'utf8');
}
module.exports = {REPO_ROOT,codec,SCHEMA_VERSION,POLICY_VERSION,CONTEXT_BOUNDARY,INDEX_KIND,MODULE_KIND,
  RELEASE_KIND,TRUST_STATUS,DECISIONS,GENERATED,PIN,LIMITS,assertAncestors,contractInventory,assertEmptyDecisions,disjoint,pinSource};
